#!/usr/bin/env bash
# Build a signed, notarized, Sparkle-ready ClaudeCodeUsage.dmg.
#
# Usage: ./Scripts/release.sh <version>
#   e.g. ./Scripts/release.sh 1.0.0
#
# One-time setup (see docs/RELEASE.md or RTKInfos' for the original writeup):
#   1. Sparkle EdDSA signing key:
#      ClaudeCodeUsage reuses the MarkdownViewer EdDSA key (Keychain account
#      "MarkdownViewer"); its public half is in Info.plist > SUPublicEDKey
#      (9PD2SBwLL4XoycyAGzaE+gO7ctuxSfuFMMajiZdXhXQ=). Do NOT regenerate it —
#      that would break auto-update for every app sharing this key.
#
#   2. Notarization uses the existing keychain profile "AppliMacVincentGithub"
#      (shared across Vincent's apps). To recreate it:
#        xcrun notarytool store-credentials "AppliMacVincentGithub" \
#          --apple-id "vincent@lauriat.fr" --team-id "KFLACS69T9"
#
# Override defaults:
#   SIGNING_IDENTITY="Developer ID Application: …" ./Scripts/release.sh 1.0.0
#   NOTARY_PROFILE="SomeOtherProfile"               ./Scripts/release.sh 1.0.0
#
# Publishing (step 10) creates the GitHub release and pushes appcast.xml:
#   PUBLISH=0      ./Scripts/release.sh 1.0.0   # build only, print manual steps
#   PUBLISH_YES=1  ./Scripts/release.sh 1.0.0   # skip the interactive confirmation
# Release notes are taken from release/release-notes-<version>.md when present,
# otherwise generated by `gh --generate-notes`.

set -euo pipefail

VERSION="${1:?Usage: ./Scripts/release.sh <version>  (e.g. 1.0.0)}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

# 1. Sanity check: project.yml must declare the same MARKETING_VERSION
if ! grep -q "MARKETING_VERSION: \"$VERSION\"" project.yml; then
  echo "✗ MARKETING_VERSION in project.yml does not match $VERSION" >&2
  grep "MARKETING_VERSION" project.yml | sed 's/^/    /' >&2
  echo "  Bump MARKETING_VERSION in project.yml first, then re-run." >&2
  exit 1
fi

# 1a. Sparkle monotonicity: clients compare CFBundleVersion, not the marketing version.
# Shipping a feed whose sparkle:version is <= the published one silently offers the update
# to nobody — and step 10 pushes that feed automatically, so catch it before the build.
NEW_BUILD="$(sed -n 's/.*CURRENT_PROJECT_VERSION: *"\{0,1\}\([0-9][0-9]*\)"\{0,1\}.*/\1/p' project.yml | head -1)"
if [ -z "$NEW_BUILD" ]; then
  echo "✗ Could not read CURRENT_PROJECT_VERSION from project.yml" >&2
  exit 1
fi
if [ -f "$ROOT/appcast.xml" ]; then
  CUR_BUILD="$(sed -n 's/.*<sparkle:version>\([0-9][0-9]*\)<.*/\1/p' "$ROOT/appcast.xml" | head -1)"
  if [ -n "$CUR_BUILD" ] && [ "$NEW_BUILD" -le "$CUR_BUILD" ]; then
    echo "✗ CURRENT_PROJECT_VERSION ($NEW_BUILD) must be greater than the published" >&2
    echo "  sparkle:version ($CUR_BUILD) — existing users would never be offered v$VERSION." >&2
    echo "  Bump CURRENT_PROJECT_VERSION in project.yml, then re-run." >&2
    exit 1
  fi
fi

# 1b. Publishing preflight — fail now rather than after a 5-minute notarization
PUBLISH="${PUBLISH:-1}"
BRANCH="$(git rev-parse --abbrev-ref HEAD)"
if [ "$PUBLISH" = "1" ]; then
  if ! command -v gh >/dev/null 2>&1; then
    echo "✗ gh not found. Install with: brew install gh  (or re-run with PUBLISH=0)" >&2
    exit 1
  fi
  if ! gh auth status >/dev/null 2>&1; then
    echo "✗ gh is not authenticated. Run: gh auth login  (or re-run with PUBLISH=0)" >&2
    exit 1
  fi
  if gh release view "v$VERSION" >/dev/null 2>&1; then
    echo "✗ GitHub release v$VERSION already exists — bump the version or delete it first." >&2
    exit 1
  fi
  # A leftover tag from an aborted run has no release, so `gh release view` misses it,
  # but `gh release create` would then attach to whatever commit that tag points at.
  if git rev-parse -q --verify "refs/tags/v$VERSION" >/dev/null \
     || [ -n "$(git ls-remote --tags origin "refs/tags/v$VERSION" 2>/dev/null)" ]; then
    echo "✗ Tag v$VERSION already exists (local or on origin) with no matching release." >&2
    echo "  Delete it first: git tag -d v$VERSION && git push origin :refs/tags/v$VERSION" >&2
    exit 1
  fi
  # The DMG is built from the working tree but the tag is cut from HEAD — a dirty tree
  # would ship a binary the tag does not describe. appcast.xml is exempt: step 10 rewrites it.
  DIRTY="$(git status --porcelain --untracked-files=no | grep -v ' appcast\.xml$' || true)"
  if [ -n "$DIRTY" ]; then
    echo "✗ Working tree has uncommitted changes — the DMG would not match tag v$VERSION:" >&2
    echo "$DIRTY" | sed 's/^/    /' >&2
    echo "  Commit or stash them first (or re-run with PUBLISH=0 to build only)." >&2
    exit 1
  fi
  # The release tag is cut from HEAD, so HEAD must already exist on the remote.
  git fetch --quiet origin "$BRANCH" 2>/dev/null || true
  if ! git merge-base --is-ancestor HEAD "origin/$BRANCH" 2>/dev/null; then
    echo "✗ HEAD is not on origin/$BRANCH — push your commits first (git push origin $BRANCH)." >&2
    exit 1
  fi
  if [ "$BRANCH" != "main" ]; then
    echo "⚠ Not on main (current branch: $BRANCH) — the tag and the appcast commit will target $BRANCH."
  fi
fi

# 1c. Sparkle signing key: must exist AND be the one this app ships, checked before the build.
# Learned the hard way on 1.3.1 — the key had vanished from the keychain and the script only
# found out at step 9, after a successful five-minute notarization.
SPARKLE_VERSION="2.9.1"
SPARKLE_TOOLS="$ROOT/.sparkle-tools"
SPARKLE_ACCOUNT="${SPARKLE_ACCOUNT:-MarkdownViewer}"
if [ ! -x "$SPARKLE_TOOLS/bin/sign_update" ]; then
  echo "→ Downloading Sparkle $SPARKLE_VERSION tools"
  mkdir -p "$SPARKLE_TOOLS"
  curl -fsSL "https://github.com/sparkle-project/Sparkle/releases/download/$SPARKLE_VERSION/Sparkle-$SPARKLE_VERSION.tar.xz" \
    | tar -xJ -C "$SPARKLE_TOOLS"
fi

EXPECTED_PUBKEY="$(/usr/libexec/PlistBuddy -c "Print :SUPublicEDKey" "$ROOT/ClaudeCodeUsage/Info.plist" 2>/dev/null || true)"
ACTUAL_PUBKEY="$("$SPARKLE_TOOLS/bin/generate_keys" -p --account "$SPARKLE_ACCOUNT" 2>/dev/null || true)"
# generate_keys prints "ERROR: No existing signing key found!" on stdout, not stderr, so a
# non-empty value proves nothing — only accept a well-formed ed25519 public key (32 bytes).
if ! printf '%s' "$ACTUAL_PUBKEY" | grep -qE '^[A-Za-z0-9+/]{43}=$'; then
  ACTUAL_PUBKEY=""
fi
if [ -z "$ACTUAL_PUBKEY" ]; then
  echo "✗ No Sparkle signing key in the keychain for account \"$SPARKLE_ACCOUNT\"." >&2
  echo "  Updates cannot be signed, so the appcast cannot be published." >&2
  echo "  DO NOT run generate_keys to make a new one: this key is shared by several of your" >&2
  echo "  apps, and replacing it permanently breaks auto-update for everyone already installed." >&2
  echo "  Recover it instead (Keychain Access across all keychains, a Time Machine copy of" >&2
  echo "  ~/Library/Keychains, or 'generate_keys -x' on another Mac then '-f' here)." >&2
  echo "  To build the DMG anyway and publish by hand later: PUBLISH=0 $0 $VERSION" >&2
  [ "$PUBLISH" = "1" ] && exit 1
  echo "  (PUBLISH=0 — continuing, the appcast step will be skipped.)" >&2
  SPARKLE_KEY_AVAILABLE=0
fi
SPARKLE_KEY_AVAILABLE="${SPARKLE_KEY_AVAILABLE:-1}"
if [ -n "$ACTUAL_PUBKEY" ] && [ -n "$EXPECTED_PUBKEY" ] && [ "$ACTUAL_PUBKEY" != "$EXPECTED_PUBKEY" ]; then
  echo "✗ The keychain key for \"$SPARKLE_ACCOUNT\" is not the one this app ships." >&2
  echo "    Info.plist SUPublicEDKey: $EXPECTED_PUBKEY" >&2
  echo "    keychain public key:      $ACTUAL_PUBKEY" >&2
  echo "  Signing with it would produce an appcast every existing install rejects." >&2
  exit 1
fi

# 2. Regenerate Xcode project
if ! command -v xcodegen >/dev/null 2>&1; then
  echo "✗ xcodegen not found. Install with: brew install xcodegen" >&2
  exit 1
fi
echo "→ xcodegen generate"
xcodegen generate >/dev/null

# 3. Build Release
rm -rf "$ROOT/build"
# CODE_SIGNING_ALLOWED=NO works around the macOS Sequoia com.apple.provenance
# xattr that codesign --force rejects. We sign manually below after a ditto scrub.
echo "→ xcodebuild Release"
xcodebuild -project ClaudeCodeUsage.xcodeproj \
  -scheme ClaudeCodeUsage \
  -configuration Release \
  -derivedDataPath build \
  CODE_SIGNING_ALLOWED=NO \
  build 2>&1 | tail -5

APP="$ROOT/build/Build/Products/Release/ClaudeCodeUsage.app"
if [ ! -d "$APP" ]; then
  echo "✗ Build did not produce $APP" >&2
  exit 1
fi

# 4. Stage to a clean directory (strips com.apple.provenance xattrs)
SIGNING_IDENTITY="${SIGNING_IDENTITY:?Set SIGNING_IDENTITY to your Developer ID certificate, e.g. SIGNING_IDENTITY='Developer ID Application: Your Name (TEAMID)' ./Scripts/release.sh $VERSION}"
NOTARY_PROFILE="${NOTARY_PROFILE:-AppliMacVincentGithub}"

STAGING_DIR="$(mktemp -d)"
STAGING="$STAGING_DIR/ClaudeCodeUsage.app"
echo "→ Staging to $STAGING_DIR"
ditto --norsrc --noextattr --noacl "$APP" "$STAGING"

# Apple's timestamp server is intermittently flaky — retry up to 5 times.
codesign_ts() {
  local target="$1"
  local attempt
  for attempt in 1 2 3 4 5; do
    if codesign --force --options runtime --timestamp --sign "$SIGNING_IDENTITY" "$target" 2>&1; then
      return 0
    fi
    if [ "$attempt" -lt 5 ]; then
      echo "  ↻ codesign failed (attempt $attempt/5), retrying in 5s…"
      sleep 5
    fi
  done
  echo "✗ codesign $target failed after 5 attempts" >&2
  return 1
}

# 5. Sign Sparkle.framework nested binaries (deepest first — required by notarization)
echo "→ Codesigning Sparkle.framework nested binaries"
SPARKLE_FW="$STAGING/Contents/Frameworks/Sparkle.framework"
SPARKLE_VER="$SPARKLE_FW/Versions/B"
codesign_ts "$SPARKLE_VER/Autoupdate"
codesign_ts "$SPARKLE_VER/XPCServices/Downloader.xpc"
codesign_ts "$SPARKLE_VER/XPCServices/Installer.xpc"
codesign_ts "$SPARKLE_VER/Updater.app"
codesign_ts "$SPARKLE_FW"

# 6. Sign the app itself
echo "→ Codesigning ClaudeCodeUsage.app with Developer ID + Hardened Runtime"
codesign_ts "$STAGING"
codesign --verify --strict --deep "$STAGING"

# 7. Package as DMG
RELEASE_DIR="$ROOT/release"
mkdir -p "$RELEASE_DIR"
DMG="$RELEASE_DIR/ClaudeCodeUsage-$VERSION.dmg"
rm -f "$DMG"

DMG_VOLNAME="ClaudeCodeUsage $VERSION"
DMG_LAYOUT_DIR="$STAGING_DIR/dmg-layout"
mkdir -p "$DMG_LAYOUT_DIR"
ditto --norsrc --noextattr --noacl "$STAGING" "$DMG_LAYOUT_DIR/ClaudeCodeUsage.app"
ln -s /Applications "$DMG_LAYOUT_DIR/Applications"

echo "→ Creating DMG"
RW_DMG="$STAGING_DIR/temp.dmg"
hdiutil create -volname "$DMG_VOLNAME" -srcfolder "$DMG_LAYOUT_DIR" \
  -fs HFS+ -format UDRW -ov "$RW_DMG" >/dev/null

DMG_MOUNT=$(hdiutil attach -nobrowse -noverify -noautoopen "$RW_DMG" \
  | awk -F '\t' 'END {print $NF}')

osascript <<APPLESCRIPT
tell application "Finder"
    tell disk "$DMG_VOLNAME"
        open
        set current view of container window to icon view
        set toolbar visible of container window to false
        set statusbar visible of container window to false
        set the bounds of container window to {200, 100, 740, 480}
        set view_options to the icon view options of container window
        set arrangement of view_options to not arranged
        set icon size of view_options to 128
        set position of item "ClaudeCodeUsage.app" of container window to {140, 200}
        set position of item "Applications" of container window to {400, 200}
        update without registering applications
        delay 1
        close
    end tell
end tell
APPLESCRIPT

sync
hdiutil detach "$DMG_MOUNT" -quiet

echo "→ Converting to compressed DMG"
hdiutil convert "$RW_DMG" -format UDZO -imagekey zlib-level=9 -ov -o "$DMG" >/dev/null
rm -rf "$STAGING_DIR"

# 8. Notarize + staple
echo "→ Submitting to Apple notary service (2–5 min)"
xcrun notarytool submit "$DMG" \
  --keychain-profile "$NOTARY_PROFILE" \
  --wait

echo "→ Stapling notarization ticket"
xcrun stapler staple "$DMG"
xcrun stapler validate "$DMG"

# 9. Sparkle EdDSA signature + appcast.xml (tools and key already checked in step 1c)
if [ "$SPARKLE_KEY_AVAILABLE" != "1" ]; then
  DMG_SIZE=$(ls -lh "$DMG" | awk '{print $5}')
  echo ""
  echo "✅ Built, signed, notarized, stapled: $DMG ($DMG_SIZE)"
  echo "⚠️  NOT Sparkle-signed — appcast.xml left untouched, no update will be advertised."
  echo "   Recover the signing key, then sign this very DMG (no rebuild, no re-notarization):"
  echo "     .sparkle-tools/bin/sign_update --account \"$SPARKLE_ACCOUNT\" \"$DMG\""
  echo "   and add the resulting edSignature to appcast.xml."
  exit 0
fi

echo "→ Signing DMG with Sparkle EdDSA key"
SPARKLE_SIG_LINE=$("$SPARKLE_TOOLS/bin/sign_update" --account "$SPARKLE_ACCOUNT" "$DMG")

# sparkle:version must be CFBundleVersion (monotonic integer), NOT the marketing version.
BUILD_NUMBER=$(/usr/libexec/PlistBuddy -c "Print :CFBundleVersion" "$APP/Contents/Info.plist")

echo "→ Writing appcast.xml (sparkle:version=$BUILD_NUMBER, shortVersion=$VERSION)"
PUB_DATE=$(date -R)
cat > "$ROOT/appcast.xml" <<APPCAST
<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:sparkle="http://www.andymatuschak.org/xml-namespaces/sparkle">
  <channel>
    <title>ClaudeCodeUsage</title>
    <link>https://raw.githubusercontent.com/vincentlauriat/ClaudeCodeUsage/main/appcast.xml</link>
    <description>ClaudeCodeUsage release feed</description>
    <language>en</language>
    <item>
      <title>v$VERSION</title>
      <pubDate>$PUB_DATE</pubDate>
      <sparkle:version>$BUILD_NUMBER</sparkle:version>
      <sparkle:shortVersionString>$VERSION</sparkle:shortVersionString>
      <sparkle:minimumSystemVersion>14.0</sparkle:minimumSystemVersion>
      <sparkle:releaseNotesLink>https://github.com/vincentlauriat/ClaudeCodeUsage/releases/tag/v$VERSION</sparkle:releaseNotesLink>
      <enclosure
        url="https://github.com/vincentlauriat/ClaudeCodeUsage/releases/download/v$VERSION/ClaudeCodeUsage-$VERSION.dmg"
        type="application/octet-stream"
        $SPARKLE_SIG_LINE />
    </item>
  </channel>
</rss>
APPCAST

DMG_SIZE=$(ls -lh "$DMG" | awk '{print $5}')
echo ""
echo "✅ Built, signed, notarized, stapled, Sparkle-signed: $DMG ($DMG_SIZE)"
echo "✅ appcast.xml updated for v$VERSION"
echo ""

manual_steps() {
  echo "Remaining steps (run manually):"
  echo "  1. gh release create v$VERSION \"$DMG\" --title \"v$VERSION\" --generate-notes"
  echo "  2. git add appcast.xml && git commit -m 'release: appcast for v$VERSION' && git push origin $BRANCH"
  echo ""
  echo "Order matters: publish the release first, so the DMG URL in appcast.xml resolves"
  echo "before Sparkle clients can read the new feed."
}

# 10. Publish: GitHub release (with the DMG) then push the appcast
if [ "$PUBLISH" != "1" ]; then
  echo "→ PUBLISH=0 — not publishing."
  manual_steps
  exit 0
fi

if [ -t 0 ] && [ "${PUBLISH_YES:-0}" != "1" ]; then
  printf "Publish GitHub release v%s and push appcast.xml to origin/%s? [y/N] " "$VERSION" "$BRANCH"
  # `|| reply=""` so that Ctrl-D (EOF) aborts cleanly instead of tripping `set -e`.
  read -r reply || reply=""
  case "$reply" in
    [yY]*) ;;
    *) echo "→ Aborted before publishing."; echo ""; manual_steps; exit 0 ;;
  esac
fi

# The release is created before the appcast is pushed: the enclosure URL must
# already resolve by the time Sparkle clients see the new feed.
NOTES_FILE="$RELEASE_DIR/release-notes-$VERSION.md"
echo "→ Creating GitHub release v$VERSION (tag on $(git rev-parse --short HEAD))"
if [ -f "$NOTES_FILE" ]; then
  gh release create "v$VERSION" "$DMG" \
    --title "v$VERSION" \
    --target "$(git rev-parse HEAD)" \
    --notes-file "$NOTES_FILE"
else
  echo "  (no $NOTES_FILE — generating notes from commit history)"
  gh release create "v$VERSION" "$DMG" \
    --title "v$VERSION" \
    --target "$(git rev-parse HEAD)" \
    --generate-notes
fi

echo "→ Committing and pushing appcast.xml"
git add appcast.xml
if git diff --cached --quiet -- appcast.xml; then
  echo "  appcast.xml unchanged — nothing to commit"
else
  git commit -m "release: appcast for v$VERSION"
  git push origin "$BRANCH"
fi

echo ""
echo "✅ GitHub release published: $(gh release view "v$VERSION" --json url --jq .url)"
echo "✅ appcast.xml live at https://raw.githubusercontent.com/vincentlauriat/ClaudeCodeUsage/main/appcast.xml"
echo ""
echo "Sparkle clients on older versions will be offered the update on next check."
